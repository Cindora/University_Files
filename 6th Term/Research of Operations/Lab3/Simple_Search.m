clc;
clear;

% Количество точек
N = 100000;

% Диапазоны
A = -21; B = 4;
C = -17; D = 27;

% Функция
f = @(x1,x2) (x1 - 2*x2).^2 + (x2 - 3).^2;

% Генерация случайных точек
x1 = A + (B - A) * rand(N,1);
x2 = C + (D - C) * rand(N,1);

% Вычисление значений функции
y = f(x1,x2);

% Поиск минимума
[min_val, idx] = min(y);
x1_min = x1(idx);
x2_min = x2(idx);

% Вывод первых 20 значений
disp('Первые 20 точек и значений функции:');
disp(table(x1(1:20), x2(1:20), y(1:20)));

% Итог
fprintf('Минимум найден:\n');
fprintf('x1 = %.4f, x2 = %.4f\n', x1_min, x2_min);
fprintf('f_min = %.6f\n', min_val);